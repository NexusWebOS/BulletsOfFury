"""Normalize authored ace armor to blue; preserve luminance/alpha and bake hit silhouettes."""
from pathlib import Path
from PIL import Image
import json, hashlib

R = Path(__file__).resolve().parents[1]
S = R / 'assets/game/encounters_0930'
O = R / 'assets/game/sky_repair_1004i'
O.mkdir(exist_ok=True)
names = ['ace', 'ace_body', 'ace_wing_l', 'ace_wing_r', 'ace_body_damage', 'ace_wing_l_damage', 'ace_wing_r_damage']
art, records = {}, []
blue = (.14, .37, .98)
weights = (.2126, .7152, .0722)
blue_y = sum(c*w for c, w in zip(blue, weights))
for name in names:
    source = S / (name + '.png')
    original = Image.open(source).convert('RGBA')
    image = original.copy()
    px = image.load()
    changed = 0
    max_luma_error = 0
    for y in range(image.height):
        for x in range(image.width):
            r, g, b, a = px[x, y]
            u, frame = x % 176, x // 176
            # The engine pods stay chrome. Their position reverses in underside
            # views; broad plate surfaces outside these measured pods are armor.
            belly = name == 'ace' and frame in (2, 8, 16)
            engine = 69 <= u <= 110 and (14 <= y <= 60 or belly and 106 <= y <= 151)
            value = max(r, g, b)
            if not a or engine or value < 28 or value > 210 or max(r,g,b)-min(r,g,b) > 30:
                continue
            rgb = [r/255, g/255, b/255]
            lum = sum(c*w for c,w in zip(rgb,weights))
            delta = [c-blue_y for c in blue]
            strength = min(.75, *(min((1-lum)/d if d>0 else lum/-d, .75) for d in delta if d))
            new = [round(255*(lum+strength*d)) for d in delta]
            px[x,y] = (*new, a)
            changed += 1
            max_luma_error = max(max_luma_error, abs(sum(c*w for c,w in zip(new,weights))-lum*255))
    image.save(O / (name + '.png'))
    white = Image.new('RGBA', image.size, (255,255,255,0))
    white.putalpha(original.getchannel('A'))
    white.save(O / (name + '_flash.png'))
    assert image.getchannel('A').tobytes() == original.getchannel('A').tobytes()
    art[name] = {'key': 'sky4i_'+name, 'flash': 'sky4i_'+name+'_flash', 'frames': [[f*176,0,176,184] for f in range(image.width//176)]}
    records.append({'name':name, 'source':str(source.relative_to(R)).replace('\\','/'),
                    'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
                    'changed_armor_pixels':changed, 'max_luminance_rounding_error':max_luma_error, 'alpha_identical':True})
manifest = {'method':'Authored source pixel palette normalization; gray armor mapped to blue at equal Rec.709 luminance. Chrome engine masks, colored engine/ordnance pixels, highlights, outlines and alpha retained. White flash PNGs use exact source alpha.', 'art':art,'sources':records}
(O/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
js = '/* Generated by build_sky_repair_1004i.py; source pixels and pivots preserved. */\nconst SKY4I_ART='+json.dumps(art,separators=(',',':'))+';\nfor(const [name,a] of Object.entries(SKY4I_ART)){XART._src[a.key]="assets/game/levels/stage_06/boss/sky_repair_1004i/"+name+".png";XART._src[a.flash]="assets/game/levels/stage_06/boss/sky_repair_1004i/"+name+"_flash.png";}\n'
(R/'assets/sky_repair_art_1004i.js').write_text(js,encoding='utf-8')
taxonomy = R/'assets/data/ART_TAXONOMY.json'
data = json.loads(taxonomy.read_text(encoding='utf-8'))
data['sky4i_'] = {'role':'boss_airframe_and_hit_flash','sheet':None,'note':'Stage 6 / X larger Nightwing ace: equal-luminance blue armor from reviewed enc30 source, exact-alpha white hit PNGs for all 20 poses and six module plates. Generated registration and manifest owned by build_sky_repair_1004i.py. Original sources retained; no packed atlas edits.'}
taxonomy.write_text(json.dumps(data,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
contact = Image.new('RGBA', (176*5,184*4),(10,12,18,255))
sheet = Image.open(O/'ace.png')
for f in range(20):contact.alpha_composite(sheet.crop((f*176,0,(f+1)*176,184)),((f%5)*176,(f//5)*184))
T = R/'_shots/sky_repair_1004i';T.mkdir(exist_ok=True)
contact.save(T/'all-ace-poses.png')
print('Blue armor and exact-alpha white frames:',len(names),'families, 20 full poses.')
