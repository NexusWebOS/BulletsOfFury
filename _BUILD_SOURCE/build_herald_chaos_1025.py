"""Red palette of the existing authored eight-frame void orb; no new silhouette.

Keep every alpha, outline, neutral metal and white glint. One128px canvas and
64,64 pivot across the complete bank. This builder owns its sheet AND registry.
"""
from pathlib import Path
from PIL import Image
import json,hashlib

R=Path(__file__).resolve().parents[1]
source=R/'assets/game/shared/player_weapons/boss_projectile_overhaul'
out=R/'assets/game/levels/stage_08/miniboss/herald_chaos_1025'
out.mkdir(parents=True,exist_ok=True)
sheet=Image.new('RGBA',(1024,128));sources=[]
for i in range(8):
 p=source/f'bpfx_proj_void_{i}.png';im=Image.open(p).convert('RGBA')
 assert im.size==(128,128)
 pixels=[]
 for r,g,b,a in im.getdata():
  if a and max(r,b)>max(38,g*1.18) and g<205:
   v=max(r,b);r=min(255,round(v*1.10+8));b=round(g*.40+v*.07);g=round(g*.50+v*.06)
  pixels.append((r,g,b,a))
 red=Image.new('RGBA',im.size);red.putdata(pixels)
 assert red.getchannel('A').tobytes()==im.getchannel('A').tobytes()
 sheet.paste(red,(i*128,0))
 sources.append({'path':p.relative_to(R).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()})
path=out/'chaos_orb.webp';sheet.save(path,lossless=True,method=6)
art={'key':'hb25_chaos_orb','path':path.relative_to(R).as_posix(),'w':128,'h':128,'frames':8,'fps':18,'pivot':[64,64],
 'cells':[[i*128,0,128,128]for i in range(8)],'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
(R/'assets/herald_chaos_art_1025.js').write_text('// Generated by _BUILD_SOURCE/build_herald_chaos_1025.py.\nconst HB25_ART='+json.dumps(art,separators=(',',':'))+';\n',encoding='utf8',newline='\n')
(out/'manifest.json').write_text(json.dumps({'art':art,'sources':sources,'recipe':__doc__},indent=2),encoding='utf8')
print(json.dumps({'bytes':path.stat().st_size,'frames':8,'alphaIdentical':True}))
