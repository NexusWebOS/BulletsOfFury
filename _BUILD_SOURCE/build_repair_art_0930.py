from pathlib import Path
from PIL import Image
import json,shutil
root=Path(__file__).resolve().parents[1]
pack=root/'assets/game/weapon_animation_0928';families=json.loads((pack/'manifest.json').read_text())['families'];reg={}
for name,d in families.items():
    if not (name.startswith(('orb_','cast_','chaingun_')) or name=='chromium_activation_hammer_only'):continue
    boxes=[Image.open(pack/f['file']).getbbox() for f in d['frames']]
    box=(min(b[0] for b in boxes),min(b[1] for b in boxes),max(b[2] for b in boxes),max(b[3] for b in boxes))
    reg[name]={'key':'repair30_'+name,'path':'assets/game/shared/player_weapons/weapon_animation_0928/'+d['atlas'],'frames':[f['rect'] for f in d['frames']],'fps':d['fps'],'anchor':d['anchor'],'size':d['size'],'ink':[box[0],box[1],box[2]-box[0],box[3]-box[1]]}
src=Path('C:/Users/Mike/.codex/generated_images/01a0c9fd-a6cc-73a3-8dca-3e0f7a90a956/exec-8f62447f-ff37-4ffd-81fb-80abbf064e8c.png')
out=root/'assets/game/repair_0930';out.mkdir(parents=True,exist_ok=True)
sources=root/'_ART_SOURCES/repair_0930';sources.mkdir(parents=True,exist_ok=True)
if not (sources/'shield.png').exists():shutil.copy2(src,sources/'shield.png')
src=sources/'shield.png'
im=Image.open(src).convert('RGBA');cw=im.width/4;ch=im.height/2
cells=[im.crop((round(i%4*cw),round(i//4*ch),round((i%4+1)*cw),round((i//4+1)*ch))) for i in range(8)]
bounds=[c.getchannel("A").point(lambda a:255 if a>32 else 0).getbbox() for c in cells];box=(min(b[0] for b in bounds),min(b[1] for b in bounds),max(b[2] for b in bounds),max(b[3] for b in bounds))
atlas=Image.new('RGBA',(8*96,128))
for i,c in enumerate(cells):
    c=c.crop(box).resize((88,120),Image.Resampling.NEAREST);atlas.alpha_composite(c,(i*96+4,4))
atlas.save(out/'shield.png')
reg['shield']={'key':'repair30_shield','path':'assets/game/shared/combat/repair_0930/shield.png','frames':[[i*96,0,96,128] for i in range(8)],'fps':12,'ink':[4,4,88,120]}
(sources/'provenance.json').write_text(json.dumps({'shieldSource':str(src),'tool':'built-in image_gen','processing':'Shared row cuts and bounding box, nearest-neighbour 8-frame atlas; preserved generated alpha.'},indent=2))
(out/'manifest.json').write_text(json.dumps(reg,indent=2),encoding='utf-8')
(root/'assets/repair_art_0930.js').write_text('/* Generated by build_repair_art_0930.py. */\nconst REPAIR30_ART='+json.dumps(reg,separators=(',',':'))+';\n',encoding='utf-8',newline='\n')
print(len(reg),'existing/generated families registered')
