"""Register the authored Phase 3 void and sixteen native-alpha code poses.

No repainting, keying, interpolation or per-frame fitting. The generator returned
1254-square code art; preserve every source pixel and pad its equal grid to even
320-square game frames. The 1024x1536 environment stays at its native resolution.
"""
from pathlib import Path
from PIL import Image
import hashlib, json, shutil

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / '_ART_SOURCES/void_arena_1011'
OUT = ROOT / 'assets/game/levels/stage_08/stage/void_arena_1011'
OUT.mkdir(parents=True, exist_ok=True)

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def entry(name, index, path, im, **extra):
    assert im.width % 2 == im.height % 2 == 0
    return dict(key=f'av11_{name}_{index}', path=path.relative_to(ROOT).as_posix(),
                w=im.width, h=im.height, pivot=[im.width//2, im.height//2],
                sha256=digest(path), **extra)

back = SRC / 'returned/void-depth.png'
dest = OUT / 'void-depth.png'
shutil.copyfile(back, dest)
im = Image.open(dest)
art = {'back': [entry('back', 0, dest, im)]}
raw = Image.open(SRC / 'returned/code-loop.png')
assert raw.mode == 'RGBA' and raw.getextrema()[3][0] == 0
bank = []
for i in range(16):
    x0, x1 = [round(n*raw.width/4) for n in (i%4, i%4+1)]
    y0, y1 = [round(n*raw.height/4) for n in (i//4, i//4+1)]
    cell = raw.crop((x0, y0, x1, y1))
    assert cell.width <= 320 and cell.height <= 320
    dx, dy = (320-cell.width)//2, (320-cell.height)//2
    padded = Image.new('RGBA', (320, 320))
    padded.paste(cell, (dx, dy))  # copy alpha verbatim; no alpha-over attenuation
    path = OUT / f'code_{i:02d}.png'
    padded.save(path, optimize=True)
    bank.append(entry('code', i, path, padded, sourceRect=[x0,y0,x1-x0,y1-y0],
                      padding=[dx,dy], scale=1))
assert len({a['sha256'] for a in bank}) == 16
art['code'] = bank
(ROOT/'assets/void_arena_art_1011.js').write_text(
    '"use strict";\n// Generated by _BUILD_SOURCE/build_void_arena_1011.py.\nconst AV11_ART='
    +json.dumps(art,separators=(',',':'))+';\n', encoding='utf-8', newline='\n')
manifest = dict(generator='built-in image_gen', sources=[
    dict(path=p.relative_to(ROOT).as_posix(),sha256=digest(p))
    for p in [back,SRC/'returned/code-loop.png']],
    prompts='_ART_SOURCES/void_arena_1011/prompts.json',
    processing='Native pixel copy and transparent padding only; common scale 1.', art=art)
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
tax = ROOT/'assets/data/ART_TAXONOMY.json'
data = json.loads(tax.read_text(encoding='utf-8'))
data['av11_'] = dict(role='stage8_phase3_boundless_alien_void_and_code_parallax',sheet=None,
    note='October11: authored 1024x1536 black/crimson atmospheric void with no architecture; sixteen native-alpha emerald code poses padded to320x320 at pivot160,160, common scale1. Sources/prompts in _ART_SOURCES/void_arena_1011. Owner build_void_arena_1011.py registers loose pixels and void_arena_art_1011.js together. Runtime void_arena_1011.js replaces only Phase3 environment, with simulation-owned clocks, proportional background cover and depth-separated code; no old back/front ribs. All encounter controllers, geometry, phase transitions and other biomes retained.')
tax.write_text(json.dumps(data,indent=2,ensure_ascii=False)+'\n',encoding='utf-8',newline='\n')
print('Registered one 1024x1536 void plate and sixteen unique 320x320 code frames.')
