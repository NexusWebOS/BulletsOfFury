#!/usr/bin/env python3
"""shield_fit_1018.py - measure each pilot's shield shell (P2_ART.shield, part2_1010/shield_<pk>.png) offline.

Mike: "all player shields need to be glowing an animated and properly centered with them."

The shell is a crystal outline with a SHIP-SHAPED HOLE in it, and the hull must sit in that hole. The old draw
scaled the whole plate by a hand-picked 1.85 x 1.65 about the plate centre, so where the hole landed depended on
how far the hole sat off the plate centre - different on every pilot. This measures the hole itself: every
transparent pixel the border flood cannot reach. Writes assets/shield_fit_1018.js (SHIELD_FIT_1018[pk] =
{plate:[w,h], hole:[x0,y0,x1,y1], rim:[x0,y0,x1,y1]}). getImageData is never needed at runtime.

    python _BUILD_SOURCE/shield_fit_1018.py [--check]
"""
import os, sys, json
from collections import deque
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'game', 'shared', 'combat', 'part2_1010')
OUT = os.path.join(ROOT, 'assets', 'shield_fit_1018.js')
PILOTS = ['cole', 'maverick', 'lizzie', 'juggernaut', 'yuri', 'freezer', 'falva', 'decker', 'axel']
SOLID = 40

def measure(path):
    im = Image.open(path).convert('RGBA'); w, h = im.size; a = im.getchannel('A').load()
    outside = bytearray(w * h); q = deque()
    for x in range(w):
        for y in (0, h - 1): q.append((x, y))
    for y in range(h):
        for x in (0, w - 1): q.append((x, y))
    while q:
        x, y = q.popleft(); i = y * w + x
        if outside[i] or a[x, y] >= SOLID: continue
        outside[i] = 1
        if x > 0: q.append((x - 1, y))
        if x < w - 1: q.append((x + 1, y))
        if y > 0: q.append((x, y - 1))
        if y < h - 1: q.append((x, y + 1))
    hx0 = hy0 = 10 ** 9; hx1 = hy1 = -1; holes = 0
    for y in range(h):
        for x in range(w):
            if a[x, y] < SOLID and not outside[y * w + x]:
                holes += 1; hx0 = min(hx0, x); hy0 = min(hy0, y); hx1 = max(hx1, x + 1); hy1 = max(hy1, y + 1)
    return im, {'plate': [w, h], 'hole': [hx0, hy0, hx1, hy1], 'rim': list(im.getbbox()), 'holePx': holes}

def main():
    fit = {}
    for pk in PILOTS:
        im, m = measure(os.path.join(SRC, 'shield_%s.png' % pk))
        assert m['holePx'] > 2000, (pk, m)
        fit[pk] = m
        hc = ((m['hole'][0] + m['hole'][2]) / 2 - m['plate'][0] / 2, (m['hole'][1] + m['hole'][3]) / 2 - m['plate'][1] / 2)
        print('%-10s hole %s  (%dx%d, centre off plate centre %+.0f,%+.0f)  rim %s' % (pk, m['hole'], m['hole'][2] - m['hole'][0], m['hole'][3] - m['hole'][1], hc[0], hc[1], m['rim']))
        if '--check' in sys.argv:
            from PIL import ImageDraw
            pr = Image.new('RGBA', im.size, (30, 30, 30, 255)); pr.paste(im, (0, 0), im)
            ImageDraw.Draw(pr).rectangle(m['hole'], outline=(255, 0, 255, 255))
            d = os.path.join(ROOT, '_shots', 'shield_1018'); os.makedirs(d, exist_ok=True); pr.save(os.path.join(d, 'hole_%s.png' % pk))
    js = ('"use strict";\n/* Generated by _BUILD_SOURCE/shield_fit_1018.py - do not edit by hand. Each pilot shield shell\'s\n'
          '   ship-shaped hole (transparent pixels the border flood cannot reach) and its rim, in plate pixels. */\n'
          'const SHIELD_FIT_1018=%s;\n') % json.dumps({k: {kk: v[kk] for kk in ('plate', 'hole', 'rim')} for k, v in fit.items()}, separators=(',', ':'))
    open(OUT, 'w', encoding='utf-8', newline='\n').write(js); print('wrote', OUT)

if __name__ == '__main__':
    main()
