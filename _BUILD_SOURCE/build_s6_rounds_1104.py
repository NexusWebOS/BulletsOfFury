"""Stage 6 fighter round bank (S6R14): the original amber flame slug at full size.

    python _BUILD_SOURCE/build_s6_rounds_1104.py

The airframe_1101 slug bank recoloured the source cyan and shrank it to ~13x5 px, which vanishes in
Stage 6's blue rain. This rebuilds the round from the SAME authored source (player ordnance atlas
mgcf_1_2, 16x20) with its own amber pixels, unscaled:
  - 32 directions on s1aDir's convention (cell d faces angle pi/2 + d*TAU/32, so cell 0 points down);
    the source faces up, so cell d is the source turned by pi + d*TAU/32 (nearest, no smoothing);
  - a 1 px dark seat outline added AFTER rotation, so it stays one pixel wide in every direction;
  - 4 frames: 0/2 are the source as authored; 1/3 cool the white core to pale gold and drop the tail tip.
32x32 cells, pivot 16,16, drawn at 32 game px (1 source px = 1 game px). Writes the sheet, a manifest
and assets/stage6_rounds_art_1104.js together.
"""
from pathlib import Path
import hashlib, json, math
from PIL import Image

R = Path(__file__).resolve().parents[1]
SRC = R / 'assets/game/shared/atlases/bof_player_ordnance_projectiles.png'
RECT = (2378, 3936, 16, 20)
OUT = R / 'assets/game/levels/stage_06/enemies/airframe_1101/slug_amber_1104.webp'
JS = R / 'assets/stage6_rounds_art_1104.js'
CELL, DIRS, FRAMES = 32, 32, 4
SEAT = (34, 12, 6, 235)

def frame_src(base, f):
    im = base.copy()
    if f % 2 == 1:
        px = im.load(); w, h = im.size
        for y in range(h):
            for x in range(w):
                if px[x, y][:3] == (255, 255, 255) and px[x, y][3]: px[x, y] = (255, 236, 160, 255)
        # drop the last pixel of the tail (lowest opaque row) for a one-pixel flicker
        for y in range(h - 1, -1, -1):
            row = [x for x in range(w) if px[x, y][3]]
            if row:
                for x in row: px[x, y] = (0, 0, 0, 0)
                break
    return im

def outline(im):
    a = im.split()[3]; w, h = im.size; out = Image.new('RGBA', im.size, (0, 0, 0, 0)); po = out.load(); pa = a.load()
    for y in range(h):
        for x in range(w):
            if pa[x, y] > 0: continue
            if any(0 <= x + dx < w and 0 <= y + dy < h and pa[x + dx, y + dy] > 0 for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                po[x, y] = SEAT
    out.alpha_composite(im); return out

def main():
    atlas = Image.open(SRC).convert('RGBA'); x, y, w, h = RECT
    base = atlas.crop((x, y, x + w, y + h))
    sheet = Image.new('RGBA', (CELL * DIRS, CELL * FRAMES), (0, 0, 0, 0))
    for f in range(FRAMES):
        src = frame_src(base, f)
        pad = Image.new('RGBA', (CELL, CELL), (0, 0, 0, 0)); pad.paste(src, ((CELL - w) // 2, (CELL - h) // 2))
        for d in range(DIRS):
            turn = math.pi + d * 2 * math.pi / DIRS          # screen-space clockwise turn
            cell = outline(pad.rotate(-math.degrees(turn), resample=Image.NEAREST))
            sheet.paste(cell, (d * CELL, f * CELL))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(OUT, 'WEBP', lossless=True, exact=True)
    sha = hashlib.sha256(OUT.read_bytes()).hexdigest()
    bank = {'key': 's6r14_slug', 'path': OUT.relative_to(R).as_posix(), 'cell': CELL, 'pivot': [16, 16], 'dirs': DIRS, 'frames': FRAMES,
            'cols': DIRS, 'drawSize': 32, 'sha256': sha,
            'source': {'path': SRC.relative_to(R).as_posix(), 'rect': list(RECT), 'key': 'mgcf_1_2',
                       'sha256': hashlib.sha256(base.tobytes()).hexdigest()},
            'owner': '_BUILD_SOURCE/build_s6_rounds_1104.py'}
    JS.write_text('"use strict";\n/* generated by _BUILD_SOURCE/build_s6_rounds_1104.py - do not edit */\nconst S6R14_ART=' + json.dumps({'slug': bank}) + ';\n', encoding='utf-8')
    print('wrote', OUT.relative_to(R), OUT.stat().st_size, 'bytes;', JS.relative_to(R))

if __name__ == '__main__':
    main()
