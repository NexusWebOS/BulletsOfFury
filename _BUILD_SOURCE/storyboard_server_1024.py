"""Local Storyroom editor. Run OPEN_STORYBOARD.bat; binds loopback only."""
from pathlib import Path
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler
from urllib.parse import urlsplit
import argparse, datetime, json, os, threading, webbrowser, urllib.request, math, socket

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'assets/data/storyboard_1024.json'
SCRIPT = ROOT / 'assets/storyboard_data_1024.js'
EMPTY = {'version': 1, 'overrides': {}, 'triggers': {}, 'order': []}
LOCK = threading.Lock()
FIELDS = {'who', 'text', 'bg', 'art', 'duration', 'c22', 'c22Flight', 'c22Action', 'c22Cue',
          'dispatch', 'pilotCam', 'pilotLine', 'federation', 'expression', 'title',
          'nativeShot', 'nativeStart', 'nativeDuration', 'location', 'c22Private'}
PILOTS = {'cole','axel','decker','yuri','maverick','lizzie','falva','freezer','juggernaut'}

def validate(data):
    if not isinstance(data, dict) or data.get('version') != 1:
        raise ValueError('This is not a Storyroom version 1 project.')
    edits = data.get('overrides', {})
    if not isinstance(edits, dict) or len(edits) > 200:
        raise ValueError('Invalid scene collection.')
    for scene, variants in edits.items():
        if not isinstance(scene,str) or not 1 <= len(scene) <= 100 or not isinstance(variants,dict):
            raise ValueError('Invalid scene or pilot versions.')
        for pilot, cards in variants.items():
            if pilot not in PILOTS or not isinstance(cards,list) or len(cards) > 500:
                raise ValueError('Invalid pilot or too many cards.')
            for c in cards:
                if not isinstance(c,dict) or type(c.get('source')) is not int or not -1 <= c['source'] <= 5000:
                    raise ValueError('A shot has an invalid source.')
                fields=c.get('fields',{})
                if not isinstance(fields,dict) or set(fields)-FIELDS:
                    raise ValueError('A shot contains unsupported fields.')
                if not isinstance(c.get('edited',[]),list) or set(c.get('edited',[]))-FIELDS:
                    raise ValueError('A shot has invalid edited fields.')
                for k,v in fields.items():
                    if isinstance(v,(dict,list)) or not isinstance(v,(str,int,float,bool,type(None))):
                        raise ValueError('Shot fields must be plain text, numbers or switches.')
                    if isinstance(v,str) and len(v)>12000:
                        raise ValueError('A shot field is too long.')
                    if k in {'who','text'} and not isinstance(v,str):
                        raise ValueError('Speaker and dialogue must be text.')
                    if isinstance(v,float) and not math.isfinite(v):
                        raise ValueError('Shot numbers must be finite.')
                if 'duration' in fields and (not isinstance(fields['duration'],(int,float)) or not .25 <= fields['duration'] <= 120):
                    raise ValueError('Shot duration must be between 0.25 and 120 seconds.')
                if 'expression' in fields and (not isinstance(fields['expression'],int) or not 0<=fields['expression']<=5):
                    raise ValueError('Dracodia expression must be 0–5.')
    triggers=data.get('triggers',{})
    if not isinstance(triggers,dict) or any(not isinstance(k,str) or not isinstance(v,str) or len(k)>100 or len(v)>100 for k,v in triggers.items()):
        raise ValueError('Invalid game scene bindings.')
    order=data.get('order',[])
    if not isinstance(order,list) or any(not isinstance(s,str) or len(s)>100 for s in order):
        raise ValueError('Invalid scene order.')
    # Rebuild the envelope; unknown top-level properties never become executable data.
    return {'version':1,'overrides':edits,'triggers':triggers,'order':order}

def read_project():
    return validate(json.loads(DATA.read_text(encoding='utf-8-sig'))) if DATA.exists() else json.loads(json.dumps(EMPTY))

def persist(data):
    encoded=json.dumps(validate(data),ensure_ascii=True,indent=2)+'\n'
    script='"use strict";\n// Generated by Storyroom. Edit with OPEN_STORYBOARD.bat.\n'
    script+='globalThis.BOF_STORYBOARD_DATA=JSON.parse('+json.dumps(encoded)+');\n'
    with LOCK:
        backups=ROOT/'_ART_SOURCES/storyboard_1024/backups'
        backups.mkdir(parents=True,exist_ok=True)
        if DATA.exists():
            stamp=datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f')
            (backups/(stamp+'.json')).write_bytes(DATA.read_bytes())
        DATA.parent.mkdir(parents=True,exist_ok=True)
        for path,content in [(DATA,encoded),(SCRIPT,script)]:
            temp=path.with_suffix(path.suffix+'.storyroom-tmp')
            temp.write_text(content,encoding='utf-8',newline='\n')
            os.replace(temp,path)
    return len(encoded.encode())

class Handler(SimpleHTTPRequestHandler):
    def __init__(self,*a,**kw): super().__init__(*a,directory=str(ROOT),**kw)
    def end_headers(self):
        self.send_header('Cache-Control','no-store')
        self.send_header('X-Content-Type-Options','nosniff')
        super().end_headers()
    def reply(self,status,data):
        raw=json.dumps(data).encode();self.send_response(status);self.send_header('Content-Type','application/json')
        self.send_header('Content-Length',str(len(raw)));self.end_headers();self.wfile.write(raw)
    def allowed(self):
        port=self.server.server_port
        hosts={f'127.0.0.1:{port}',f'localhost:{port}'}
        return self.headers.get('Host') in hosts and self.headers.get('Origin',f'http://127.0.0.1:{port}') in {f'http://{h}'for h in hosts}
    def do_GET(self):
        if urlsplit(self.path).path=='/api/storyboard':
            if not self.allowed():return self.reply(403,{'error':'Open Storyroom on localhost.'})
            try:return self.reply(200,{'app':'fury-storyroom','project':read_project(),'file':'assets/data/storyboard_1024.json'})
            except (ValueError,OSError) as e:return self.reply(500,{'error':str(e)})
        return super().do_GET()
    def do_POST(self):
        if urlsplit(self.path).path!='/api/storyboard/save':return self.reply(404,{'error':'Unknown action.'})
        if not self.allowed():return self.reply(403,{'error':'Only the local editor can save.'})
        try:
            length=int(self.headers.get('Content-Length','0'))
            if not 0<length<=4*1024*1024:raise ValueError('Project must be smaller than 4 MB.')
            project=validate(json.loads(self.rfile.read(length)))
            size=persist(project)
            return self.reply(200,{'ok':True,'bytes':size,'savedAt':datetime.datetime.now().isoformat(timespec='seconds')})
        except (ValueError,TypeError,json.JSONDecodeError) as e:return self.reply(400,{'error':str(e)})
        except OSError as e:return self.reply(500,{'error':str(e)})
    def log_message(self,fmt,*args):
        if args and str(args[0]).startswith('POST'):super().log_message(fmt,*args)

class StoryroomHTTPServer(ThreadingHTTPServer):
    # Windows SO_REUSEADDR can otherwise admit two listeners on the same port.
    allow_reuse_address = False
    def server_bind(self):
        if hasattr(socket,'SO_EXCLUSIVEADDRUSE'):
            self.socket.setsockopt(socket.SOL_SOCKET,socket.SO_EXCLUSIVEADDRUSE,1)
        super().server_bind()

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--port',type=int,default=8795);ap.add_argument('--no-open',action='store_true');args=ap.parse_args()
    try:server=StoryroomHTTPServer(('127.0.0.1',args.port),Handler)
    except OSError:
        try:
            with urllib.request.urlopen(f'http://127.0.0.1:{args.port}/api/storyboard',timeout=2) as response:
                existing=json.load(response)
            if existing.get('app')=='fury-storyroom':
                url=f'http://127.0.0.1:{args.port}/tools/storyboard/'
                print('Storyroom is already running: '+url)
                if not args.no_open:webbrowser.open(url)
                return
        except (OSError,ValueError):pass
        print(f'Port {args.port} is busy. If Storyroom is already open, use that window; otherwise run with --port 8796.')
        raise SystemExit(1)
    url=f'http://127.0.0.1:{server.server_port}/tools/storyboard/'
    print('Fury Storyroom: '+url,flush=True)
    print('Apply to Game saves the dialogue and its runtime data. Close this window to stop the editor.',flush=True)
    if not args.no_open:webbrowser.open(url)
    try:server.serve_forever()
    except KeyboardInterrupt:pass
    finally:server.server_close()

if __name__=='__main__':main()
