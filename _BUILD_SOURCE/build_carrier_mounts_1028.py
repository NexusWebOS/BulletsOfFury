"""Measure physical laser barrel mouths from all existing Carrier turret cells.

No raster pixels are changed. The directional/recoil bank is already exported
at its live display size; applying hull scale again would detach the muzzle.
"""
from pathlib import Path
import json,hashlib,math
import numpy as np
from PIL import Image

R=Path(__file__).resolve().parents[1]
s=(R/'assets/encounter_revision_art_1027.js').read_text()
a=json.loads(s[s.index('{'):s.rindex('}')+1])['carrier_turret']
image=np.array(Image.open(R/a['path']).convert('RGBA'));muzzles=[]
for f in range(a['frames']):
 x=f%a['cols']*a['cw'];y=f//a['cols']*a['ch'];cell=image[y:y+a['ch'],x:x+a['cw']]
 yy,xx=np.where(cell[:,:,3]>=128);xy=np.column_stack([xx+.5-a['pivot'][0],yy+.5-a['pivot'][1]])
 angle=math.pi/2+(f%64)*math.tau/64
 direction=np.array([math.cos(angle),math.sin(angle)]);side=np.array([-direction[1],direction[0]])
 distance=xy@direction;cross=xy@side;lane=np.abs(cross)<6
 front=distance[lane].max();points=xy[lane&(distance>front-.65)]
 assert front>20 and len(points),f
 mouth=points.mean(axis=0)+np.array(a['pivot'])+direction*.25
 muzzles.append([round(float(v),3)for v in mouth])
data=dict(source=a['path'],sourceSha256=hashlib.sha256((R/a['path']).read_bytes()).hexdigest(),cell=[a['cw'],a['ch']],pivot=a['pivot'],directions=64,cycles=4,muzzles=muzzles)
(R/'assets/carrier_turret_sockets_1028.js').write_text('"use strict";\n// Generated by _BUILD_SOURCE/build_carrier_mounts_1028.py from the unchanged native turret pixels.\nconst HC32_LASER_SOCKETS='+json.dumps(data,separators=(',',':'))+';\n',encoding='utf8')
print('Measured256 native directional/recoil barrel mouths; no raster changes.')
