sheet=Image.new('RGBA',(240*5,320*2),(5,20,32,255))
for n in range(1,10):sheet.alpha_composite(Image.open(O/f'flag_{n}_av.png'),(((n-1)%5)*240,((n-1)//5)*320))
sheet.alpha_composite(x,(960,320))
sheet.save(O/'flags_preview.png')
